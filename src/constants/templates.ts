// ===================== All templates =====================

export const ALL_TEMPLATES: VideoTemplate[] = [
  ...QUICK_ADS_TEMPLATES,
  ...REVIEW_VIDEO_TEMPLATES,
  ...CONVERSION_VIDEO_TEMPLATES,
];

export function getTemplatesByPackage(packageType: PackageType): VideoTemplate[] {
  return ALL_TEMPLATES.filter(t => t.package_type === packageType);
}

export function getTemplateById(templateId: string): VideoTemplate | undefined {
  return ALL_TEMPLATES.find(t => t.template_id === templateId);
}
